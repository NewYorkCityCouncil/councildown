// Builds tokens/*.json into generated/ (CSS, Tailwind, JSON, R) and src/generated/ (TypeScript).
// Run: npm run build
import StyleDictionary from 'style-dictionary';
import { readFileSync } from 'node:fs';

const HEADER = 'Generated by design-tokens/build.mjs. Do not edit by hand; edit design-tokens/tokens/*.json instead.';

// Palette kind (sequential / categorical / diverging) lives on the group, not the tokens.
const paletteSource = JSON.parse(readFileSync(new URL('./tokens/palette.json', import.meta.url))).palette;
const paletteKinds = Object.fromEntries(
  Object.entries(paletteSource)
    .filter(([k]) => !k.startsWith('$'))
    .map(([k, g]) => [k, g.$extensions?.nycc?.kind ?? 'sequential']),
);

const camel = (s) => s.replace(/[-_ ]+([a-z0-9])/gi, (_, c) => c.toUpperCase());
const snake = (s) => s.replace(/[- ]+/g, '_');

// Nest tokens by path. Palettes become ordered arrays.
function toTree(tokens, keyFn) {
  const tree = {};
  for (const t of tokens) {
    const [top, ...rest] = t.path;
    if (top === 'palette') {
      const [name, step] = rest;
      const arr = ((tree.palette ??= {})[name] ??= []);
      arr[Number(step) - 1] = t.$value;
      continue;
    }
    let node = (tree[keyFn(top)] ??= {});
    rest.slice(0, -1).forEach((k) => (node = node[keyFn(k)] ??= {}));
    node[keyFn(rest.at(-1))] = t.$value;
  }
  return tree;
}

StyleDictionary.registerFormat({
  name: 'nycc/typescript',
  format: ({ dictionary }) => {
    const tree = toTree(dictionary.allTokens, camel);
    const lines = [`// ${HEADER}`, ''];
    for (const [k, v] of Object.entries(tree)) {
      const name = k === 'palette' ? 'palettes' : k === 'color' ? 'colors' : k === 'font' ? 'fonts' : k;
      lines.push(`export const ${name} = ${JSON.stringify(v, null, 2)} as const;`, '');
    }
    lines.push(`export const paletteKinds = ${JSON.stringify(paletteKinds, null, 2)} as const;`, '');
    lines.push('export type ColorName = keyof typeof colors;');
    lines.push('export type PaletteName = keyof typeof palettes;', '');
    return lines.join('\n');
  },
});

StyleDictionary.registerFormat({
  name: 'nycc/json',
  format: ({ dictionary }) =>
    JSON.stringify({ ...toTree(dictionary.allTokens, camel), paletteKinds }, null, 2) + '\n',
});

// R: nycc_colors keeps original R names; everything else is nested lists.
const rValue = (v) => (typeof v === 'number' ? String(v) : JSON.stringify(v));
const rList = (obj, indent = '  ') =>
  'list(\n' +
  Object.entries(obj)
    .map(([k, v]) => {
      const val = Array.isArray(v)
        ? `c(${v.map(rValue).join(', ')})`
        : typeof v === 'object'
          ? rList(v, indent + '  ')
          : rValue(v);
      return `${indent}${k} = ${val}`;
    })
    .join(',\n') +
  `\n${indent.slice(2)})`;

StyleDictionary.registerFormat({
  name: 'nycc/r',
  format: ({ dictionary }) => {
    const tokens = dictionary.allTokens;
    const tree = toTree(tokens, snake);
    const colors = tokens
      .filter((t) => t.path[0] === 'color')
      .map((t) => `  "${t.$extensions?.nycc?.rName ?? t.path[1]}" = "${t.$value}"`);
    return [
      `# ${HEADER}`,
      '',
      `nycc_colors <- c(\n${colors.join(',\n')}\n)`,
      '',
      `nycc_palettes <- ${rList(tree.palette)}`,
      '',
      `nycc_fonts <- ${rList(tree.font)}`,
      '',
      `nycc_chart <- ${rList(tree.chart)}`,
      '',
      `nycc_map <- ${rList(tree.map)}`,
      '',
    ].join('\n');
  },
});

// Tailwind v4 theme: bg-nycc-maroon, text-nycc-dark-blue, fill-nycc-warm-3, font-heading.
StyleDictionary.registerFormat({
  name: 'nycc/tailwind',
  format: ({ dictionary }) => {
    const kebab = (s) => s.replace(/_/g, '-');
    const lines = [
      `/* ${HEADER} */`,
      '/* Usage: @import "tailwindcss"; @import "@nycc/design/tailwind.css"; */',
      '',
      '@theme {',
    ];
    for (const t of dictionary.allTokens) {
      const [top, a, b] = t.path;
      if (top === 'color') lines.push(`  --color-nycc-${a}: ${t.$value};`);
      if (top === 'palette') lines.push(`  --color-nycc-${kebab(a)}-${b}: ${t.$value};`);
      if (top === 'font') lines.push(`  --font-${a}: ${t.$value};`);
    }
    lines.push('}', '');
    return lines.join('\n');
  },
});

const transforms = ['attribute/cti', 'name/kebab'];

const sd = new StyleDictionary({
  source: ['tokens/**/*.json'],
  usesDtcg: true,
  log: { verbosity: 'default' },
  platforms: {
    css: {
      transforms,
      prefix: 'nycc',
      buildPath: 'generated/css/',
      files: [{ destination: 'tokens.css', format: 'css/variables', options: { outputReferences: true } }],
    },
    tailwind: {
      transforms,
      buildPath: 'generated/tailwind/',
      files: [{ destination: 'theme.css', format: 'nycc/tailwind' }],
    },
    ts: {
      transforms,
      buildPath: 'src/generated/',
      files: [{ destination: 'tokens.ts', format: 'nycc/typescript' }],
    },
    json: {
      transforms,
      buildPath: 'generated/json/',
      files: [{ destination: 'tokens.json', format: 'nycc/json' }],
    },
    r: {
      transforms,
      buildPath: 'generated/r/',
      files: [{ destination: 'tokens.R', format: 'nycc/r' }],
    },
  },
});

await sd.buildAllPlatforms();
